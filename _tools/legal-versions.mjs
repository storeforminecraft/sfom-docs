import { readFileSync, writeFileSync, statSync } from 'node:fs';
import { createHash } from 'node:crypto';

const owners = {
  'ko/terms/EULA.md': 'terms.service',
  'ko/terms/PrivacyPolicy.md': 'privacy.notice',
  'ko/terms/Personal_Information_Collection_and_Use_Agreement.md': 'privacy.collection',
  'ko/terms/Personal_Information_Transfer_Agreement.md': 'privacy.overseas',
  'ko/terms/ContentOperationsPolicy.md': 'policy.content',
};
const fields = ['versionId', 'digest', 'documentKey', 'locale', 'approvalPacketSha256', 'reference'];
const invalid = message => { throw new Error(`Invalid legal mapping: ${message}`); };
const record = value => value !== null && typeof value === 'object' && !Array.isArray(value);
function validateVersionId(id) {
  if (typeof id !== 'string' || id.length > 512 || !/^sfom_[A-Za-z0-9_-]+$/.test(id)) invalid('versionId must be a canonical LegalDocumentVersion typed ID');
  let tuple;
  try { tuple = JSON.parse(new TextDecoder('utf-8', { fatal: true }).decode(Buffer.from(id.slice(5), 'base64url'))); }
  catch { invalid('versionId decoding failed'); }
  if (!Array.isArray(tuple) || tuple.length !== 3 || tuple[0] !== 1 || tuple[1] !== 'LegalDocumentVersion') invalid('wrong typed ID tuple');
  const raw = tuple[2];
  if (typeof raw !== 'string' || raw.length === 0 || raw.length > 128 || !raw.isWellFormed() || /[\u0000-\u001f\u007f-\u009f]/u.test(raw)) invalid('invalid raw version ID');
  if ('sfom_' + Buffer.from(JSON.stringify(tuple), 'utf8').toString('base64url') !== id) invalid('noncanonical versionId spelling');
}
function validate(mapping) {
  if (!record(mapping)) invalid('root must be an object');
  for (const [owner, entry] of Object.entries(mapping)) {
    if (!Object.hasOwn(owners, owner)) invalid('unknown legacy owner');
    if (!record(entry) || Object.keys(entry).length !== fields.length || fields.some(field => !Object.hasOwn(entry, field))) invalid('entry requires exactly versionId/digest/documentKey/locale/approvalPacketSha256/reference');
    validateVersionId(entry.versionId);
    if (entry.documentKey !== owners[owner] || entry.locale !== 'ko') invalid('owner documentKey/locale mismatch');
    for (const field of ['digest', 'approvalPacketSha256']) if (typeof entry[field] !== 'string' || !/^[a-f0-9]{64}$/.test(entry[field])) invalid(`${field} must be lowercase SHA-256`);
    // These are provenance pointers, not proof of human approval. Restrict the
    // literal alphabet because JSON escaping is not safe Liquid quoting.
    if (typeof entry.reference !== 'string' || !/^[A-Za-z0-9:/?&=._~%#@+\-]{1,512}$/.test(entry.reference)) invalid('reference must be a plain ASCII record pointer without quotes, whitespace or Liquid delimiters');
  }
}
function compile(mapping) {
  const lines = ['{%- comment -%}Generated by _tools/legal-versions.mjs; review with the exact mapping. Do not edit.{%- endcomment -%}'];
  const selected = Object.keys(owners).filter(owner => Object.hasOwn(mapping, owner));
  if (!selected.length) return lines.join('\n') + '\n';
  lines.push('{%- assign legal_map = site.data.legal_versions -%}', '{%- assign legal_map_count = legal_map | size -%}', `{%- assign legal_match = false -%}`, `{%- if legal_map_count == ${selected.length} -%}`, '{%- assign legal_match = true -%}');
  for (const owner of selected) {
    lines.push(`{%- assign legal_entry = legal_map['${owner}'] -%}`, '{%- assign legal_entry_count = legal_entry | size -%}');
    const guards = [`legal_entry_count == ${fields.length}`, ...fields.map(field => `legal_entry.${field} == '${mapping[owner][field]}'`)];
    lines.push(`{%- unless ${guards.join(' and ')} -%}`, '{%- assign legal_match = false -%}', '{%- endunless -%}');
  }
  lines.push('{%- endif -%}', '{%- if legal_match -%}', '{%- case page.path -%}');
  for (const owner of selected) {
    const entry = mapping[owner];
    lines.push(`{%- when '${owner}' -%}`);
    if (entry.reference === 'SFOM_KO_REVISION_20261025') {
      lines.push(`<aside class="legal-version-bridge" aria-label="이전 준비 문서" data-version-id="{{ '${entry.versionId}' | escape }}" data-content-digest="{{ '${entry.digest}' | escape }}"><p><a href="{{ 'https://api.sfom.app/legal/versions/${entry.versionId}' | escape }}">이전 준비 문서 보기</a></p><p>이 링크는 개정 준비 과정의 자료입니다. 2026년 11월 6일 시행 문서는 아래 개정 안내에서 확인해 주세요.</p></aside>`);
    } else {
    lines.push(`<aside class="legal-version-bridge" aria-label="정책 고정 버전" data-version-id="{{ '${entry.versionId}' | escape }}" data-content-digest="{{ '${entry.digest}' | escape }}"><p><a href="{{ 'https://api.sfom.app/legal/versions/${entry.versionId}' | escape }}">이 정책의 고정 버전 보기</a></p><p>연결된 버전의 게시일과 시행일을 확인할 수 있습니다. 이 페이지의 기존 본문은 아래에 계속 표시됩니다.</p><p>원문 SHA-256: <code>{{ '${entry.digest}' | escape }}</code></p></aside>`);
    }
  }
  lines.push('{%- endcase -%}', '{%- endif -%}');
  return lines.join('\n') + '\n';
}
function verifyReadback(mapping, jsonPath, headersPath, owner) {
  if (!Object.hasOwn(mapping, owner)) invalid('readback owner is not mapped');
  if (statSync(jsonPath).size > 2 * 1024 * 1024 || statSync(headersPath).size > 32768) invalid('readback exceeds local byte budget');
  const response = JSON.parse(readFileSync(jsonPath, 'utf8'));
  if (response.errors !== undefined && (!Array.isArray(response.errors) || response.errors.length)) invalid('GraphQL readback has errors');
  const version = response.data?.legalDocumentVersion;
  const entry = mapping[owner];
  if (!record(version)) invalid('published version is missing');
  for (const [field, expected] of Object.entries({ id: entry.versionId, documentKey: entry.documentKey, locale: entry.locale, digest: entry.digest })) {
    if (version[field] !== expected) invalid(`readback ${field} mismatch`);
  }
  for (const field of ['title', 'body']) if (typeof version[field] !== 'string' || !version[field].isWellFormed()) invalid(`invalid readback ${field}`);
  for (const field of ['publishedAt', 'effectiveAt']) if (!Number.isSafeInteger(version[field]) || version[field] < 0 || version[field] > 8640000000000000) invalid(`invalid readback ${field}`);
  if (version.publishedAt > Date.now()) invalid('version is not published yet');
  const digest = createHash('sha256').update(version.title + '\n' + version.body, 'utf8').digest('hex');
  if (digest !== entry.digest) invalid('original title+LF+body digest mismatch');
  const headers = readFileSync(headersPath, 'utf8');
  const statuses = [...headers.matchAll(/^HTTP\/[0-9.]+[ \t]+([0-9]{3})[^\r\n]*$/gm)];
  const digests = [...headers.matchAll(/^x-legal-content-digest:[ \t]*([^\r\n]+)\r?$/gim)];
  if (statuses.length !== 1 || statuses[0][1] !== '200' || digests.length !== 1 || digests[0][1].trim() !== entry.digest) invalid('public HTML HTTP status/digest header mismatch');
  return { owner, versionId: entry.versionId, digest: entry.digest, documentKey: entry.documentKey, locale: entry.locale, publishedAt: version.publishedAt, effectiveAt: version.effectiveAt };
}
try {
  const [command = 'check', mappingPath = '_data/legal_versions.json', outputPath = '_includes/legal-version-links.html', ...extra] = process.argv.slice(2);
  if (!['check', 'compile', 'readback'].includes(command) || (command === 'readback' ? extra.length !== 2 : extra.length !== 0)) throw new Error('Usage: node _tools/legal-versions.mjs check|compile [mapping.json] [generated-include.html] OR readback mapping.json graphql-response.json html-headers.txt owner.md');
  if (statSync(mappingPath).size > 32768) invalid('mapping exceeds 32 KiB');
  const mappingText = readFileSync(mappingPath, 'utf8');
  let mapping;
  try { mapping = JSON.parse(mappingText); } catch { invalid('invalid JSON'); }
  validate(mapping);
  if (command === 'readback') {
    const receipt = verifyReadback(mapping, outputPath, extra[0], extra[1]);
    console.log(JSON.stringify({ kind: 'legal-version-readback', ...receipt, mappingSha256: createHash('sha256').update(mappingText, 'utf8').digest('hex'), checkedAt: new Date().toISOString(), captureSource: 'operator-supplied', approvalAuthenticated: false }));
  }
  else {
    const generated = compile(mapping);
    if (command === 'compile') writeFileSync(outputPath, generated);
    else if (readFileSync(outputPath, 'utf8') !== generated) invalid('generated include is stale; compile and review both files');
  }
  console.log(`Legal mapping ${command}: OK (${Object.keys(mapping).length} entries; syntax/provenance only, no approval authentication)`);
} catch (error) {
  console.error(error.message);
  process.exitCode = 1;
}
